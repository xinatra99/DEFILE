import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const data=JSON.parse(fs.readFileSync(new URL('../demo/data/data.json',import.meta.url)));
const ctx=vm.createContext({Response,URL,structuredClone});
vm.runInContext(fs.readFileSync(new URL('../demo/data-adapter.js',import.meta.url),'utf8'),ctx);
const make=()=>ctx.DefileDemo.createAdapter(data);
test('records contain independently generated before/after analyses and a real extraction',()=>{
  assert.equal(data.reports['sample-original'].report.findings.length,5);
  assert.equal(data.reports['sample-hardened'].report.findings.length,1);
  assert.equal(data.reports['sample-corpus'].report.binaries.length,101);
  assert.equal(data.jobs.find(x=>x.id==='sample-extraction').regions.filter(x=>x.usable).length,2);
  assert.ok(data.jobs.find(x=>x.id==='sample-timeline').log.length>10);
});
test('filter, sort, paging and file lookup operate on real bundled records',async()=>{
  const api=make();
  let r=await(await api.request('/api/jobs/sample-original/findings?q=strcpy&sort=confidence')).json();
  assert.equal(r.total,1);assert.ok(r.items[0].demo_pseudocode);assert.match(r.items[0].pseudocode,/Not generated by Ghidra/);
  r=await(await api.request('/api/jobs/sample-corpus/binaries?offset=100&limit=100')).json();assert.equal(r.items.length,1);assert.equal(r.total,101);
  r=await(await api.request('/api/jobs/sample-corpus/findings?all=1')).json();assert.equal(r.items.length,305);
  const path=data.reports['sample-original'].report.files.find(x=>x.kind==='config').path;
  r=await(await api.request('/api/jobs/sample-original/file-content?path='+encodeURIComponent(path))).json();assert.match(r.content,/telnet_enable=1/);
  assert.equal((await api.request('/api/jobs/sample-original/file-content?path=/etc/passwd')).status,404);
});
test('mutations and arbitrary external calls cannot execute or change published data',async()=>{
  const api=make(),before=JSON.stringify(api.data);
  for(const [path,method] of [['/api/jobs','POST'],['/api/upload','POST'],['/api/jobs/sample-original','DELETE'],['/api/jobs/sample-original/triage','POST'],['/api/ai/providers','POST'],['/api/jobs/sample-original/ai-analysis','POST']])assert.equal((await api.request(path,{method,body:'{}'})).status,403,path);
  assert.equal((await api.request('http://localhost:8080/api/jobs')).status,403);
  assert.equal(JSON.stringify(api.data),before);assert.ok(Object.isFrozen(api.data.reports));
  const result=await(await api.request('/api/jobs')).json();result[0].target='changed';assert.notEqual(api.data.jobs[0].target,'changed');
});
test('comparison computes real changes without a backend and returns the existing UI contract',async()=>{
  const api=make(),r=await(await api.request('/api/compare',{method:'POST',body:JSON.stringify({a:'sample-original',b:'sample-hardened'})})).json();
  assert.ok(r.removedTotal>0);assert.ok(r.functionDiff.rows.length>0);assert.ok(r.functionDiff.rows.every(x=>typeof x.path==='string'));assert.ok(r.fileDiff.modified.length>0);
  const same=api.compare('sample-original','sample-original',[]);assert.equal(same.addedTotal,0);assert.equal(same.removedTotal,0);assert.equal(same.functionDiff.counts.unchanged,11);
});
test('AI notes identify their authored origin and require no credentials or inference',async()=>{
  const r=await(await make().request('/api/jobs/sample-original/ai-analysis')).json();assert.equal(r.status,'done');assert.match(r.content,/not generated by an AI provider/);assert.equal(r.model,'No model inference');
});
test('Full transport defaults still use the real fetch implementation and original URLs',async()=>{
  const calls=[];const context=vm.createContext({localStorage:{getItem:()=>null},fetch:async(...args)=>{calls.push(args);return new Response('{}');}});
  vm.runInContext(fs.readFileSync(new URL('../service/web/workbench.js',import.meta.url),'utf8'),context);
  const full=vm.runInContext('app()',context);await full.requestData('/healthz');assert.equal(calls[0][0],'/healthz');full.selectedId='full-scan';assert.match(full.exportURL('json'),/^\/api\/jobs\/full-scan\/report/);
});
